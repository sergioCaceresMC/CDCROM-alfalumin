const saved = () => masterSchema.parse(JSON.parse(localStorage.getItem(MASTER_STORAGE_KEY)!));
it("guarda y retira cartas con iconos y permite limpiar el tablero en bloque", async () => {
  vi.spyOn(window, "confirm").mockReturnValue(true);
  const user = userEvent.setup();
  render(<MemoryRouter><Master characters={[]} /></MemoryRouter>);
  await user.type(await screen.findByLabelText("Nombre de campaña"), "Limpieza");
  await user.click(screen.getByRole("button", { name: "Crear campaña" }));
  await user.click(screen.getByRole("button", { name: "Barajas y herramientas" }));
  const draw = await screen.findByRole("button", { name: "Sacar carta al azar" });
  await user.click(draw); await user.click(draw);
  await user.click(within(screen.getAllByRole("article")[0]).getByRole("button", { name: /^Guardar .* en inventario$/ }));
  expect(saved().campaigns[0].table.storedCards).toHaveLength(1);
  await user.click(within(screen.getByRole("article")).getByRole("button", { name: /^Retirar .* del tablero$/ }));
  expect(saved().campaigns[0].table.cards).toHaveLength(0);
  await user.click(draw); await user.click(draw);
  await user.click(screen.getByRole("button", { name: "Acciones del tablero" }));
  await user.click(screen.getByRole("button", { name: "Guardar todas las cartas en inventario" }));
  expect(saved().campaigns[0].table.storedCards).toHaveLength(3);
  expect(saved().campaigns[0].table.cards).toHaveLength(0);
  await user.click(draw);
  await user.click(screen.getByRole("button", { name: "Acciones del tablero" }));
  await user.click(screen.getByRole("button", { name: "Retirar cartas de la mesa" }));
  expect(saved().campaigns[0].table.cards).toHaveLength(0);
  await user.click(screen.getByRole("button", { name: "Colocar ficha roja" }));
  await user.click(screen.getByRole("button", { name: "Acciones del tablero" }));
  await user.click(screen.getByRole("button", { name: "Reiniciar tablero" }));
  expect(saved().campaigns[0].table.tokens).toHaveLength(0);
  expect(saved().campaigns[0].table.storedCards).toHaveLength(3);
});
it("carga un mapa desde el PC y conserva su tamaño al ampliarlo", async () => {
  class DecodedImage {
    naturalWidth = 600;
    naturalHeight = 300;
    onload: (() => void) | null = null;
    set src(_value: string) { queueMicrotask(() => this.onload?.()); }
  }
  vi.stubGlobal("Image", DecodedImage);
  const user = userEvent.setup();
  render(<MemoryRouter><Master characters={[]} /></MemoryRouter>);
  await user.type(await screen.findByLabelText("Nombre de campaña"), "Mapa local");
  await user.click(screen.getByRole("button", { name: "Crear campaña" }));
  await user.click(screen.getByRole("button", { name: "Barajas y herramientas" }));
  await user.click(screen.getByText("Escenario"));
  await user.upload(screen.getByLabelText("Cargar mapa como imagen"), new File([new Uint8Array([137, 80, 78, 71])], "mapa.png", { type: "image/png" }));
  await screen.findByRole("img", { name: "mapa.png" });
  expect(saved().campaigns[0].table.imageMaps[0].image).toMatch(/^data:image\/png;base64,/);
  await user.click(screen.getByRole("button", { name: "Ajustar mapa mapa.png" }));
  await user.click(screen.getByRole("button", { name: "Ampliar mapa" }));
  expect(saved().campaigns[0].table.imageMaps[0]).toMatchObject({ width: 750, height: 375 });
  await user.click(screen.getByRole("button", { name: "Retirar de la mesa" }));
  expect(saved().campaigns[0].table.imageMaps).toHaveLength(0);
});
